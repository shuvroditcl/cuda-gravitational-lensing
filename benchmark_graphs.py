import matplotlib.pyplot as plt
import numpy as np

fig, (ax1, ax2, ax3) = plt.subplots(1, 3, figsize=(18, 5.4))

# =========================================================================
# Graph A: Matches Table 3A - Resolution Scaling (N_L = 3 Lenses)
# =========================================================================
res_labels = ['801 x 801', '1601 x 1601', '4001 x 4001', '8001 x 8001']
k_speedup_a = [35.5, 94.5, 154.3, 154.9]
t_speedup_a = [4.8, 7.4, 8.3, 8.6]

ax1.plot(res_labels, k_speedup_a, marker='o', linewidth=2.2, label='Kernel Speedup', color='#0052cc')
ax1.plot(res_labels, t_speedup_a, marker='s', linewidth=2.2, label='Total Speedup', color='#ff6600')

for i, (k, t) in enumerate(zip(k_speedup_a, t_speedup_a)):
    ax1.annotate(f"{k}x", (res_labels[i], k), textcoords="offset points", xytext=(0, 7),
                 ha='center', fontsize=8.5, fontweight='bold', color='#0052cc')
    ax1.annotate(f"{t}x", (res_labels[i], t), textcoords="offset points", xytext=(0, 7),
                 ha='center', fontsize=8.5, fontweight='bold', color='#cc5200')

ax1.set_ylim(0, 180)
ax1.set_title('A. Resolution Scaling (N_L = 3 Lenses)', fontweight='bold', fontsize=11)
ax1.set_xlabel('Grid Resolution')
ax1.set_ylabel('Speedup Factor over CPU (x)')
ax1.grid(True, linestyle='--', alpha=0.6)
ax1.legend(loc='upper left')

# =========================================================================
# Graph B: Matches Table 3B - Lens System Complexity Scaling (801x801 Grid)
# =========================================================================
lenses_b = [1, 2, 3, 10, 50, 100, 500]
k_speedup_b = [25.2, 32.5, 39.9, 84.2, 180.3, 213.2, 222.8]
t_speedup_b = [2.9, 3.8, 4.9, 12.3, 51.2, 87.5, 170.8]

ax2.plot(lenses_b, k_speedup_b, marker='o', linewidth=2.2, label='Kernel Speedup', color='#0052cc')
ax2.plot(lenses_b, t_speedup_b, marker='s', linewidth=2.2, label='Total Speedup', color='#ff6600')

for x_val, k, t in zip(lenses_b, k_speedup_b, t_speedup_b):
    ax2.annotate(f"{k}x", (x_val, k), textcoords="offset points", xytext=(0, 7),
                 ha='center', fontsize=8, fontweight='bold', color='#0052cc')
    ax2.annotate(f"{t}x", (x_val, t), textcoords="offset points", xytext=(0, -13),
                 ha='center', fontsize=8, fontweight='bold', color='#cc5200')

ax2.set_xscale('log')
ax2.set_ylim(-10, 250)
ax2.set_title('B. Lens System Complexity Scaling (801x801 Grid)', fontweight='bold', fontsize=11)
ax2.set_xlabel('Lens Count (N_L, Log Scale)')
ax2.set_ylabel('Speedup Factor over CPU (x)')
ax2.grid(True, linestyle='--', alpha=0.6)
ax2.legend(loc='upper left')

# =========================================================================
# Graph C: Matches Table 3C - High-Res Multi-Lens Stress Test (4001x4001 Grid)
# =========================================================================
configs_c = ['4001x4001,\n1 Lens', '4001x4001,\n10 Lenses', '4001x4001,\n50 Lenses', '4001x4001,\n100 Lenses']
cpu_ms_c     = [87.43, 388.92, 1914.21, 3966.15]
gpu_tot_ms_c = [17.28, 18.83,  27.32,   36.66]
gpu_ker_ms_c = [0.65,  2.22,   10.67,   19.99]

x = np.arange(len(configs_c))
width = 0.26

rects1 = ax3.bar(x - width, cpu_ms_c, width, label='CPU (ms)', color='#d9534f')
rects2 = ax3.bar(x, gpu_tot_ms_c, width, label='GPU Total (ms)', color='#f0ad4e')
rects3 = ax3.bar(x + width, gpu_ker_ms_c, width, label='GPU Kernel (ms)', color='#5cb85c')

ax3.set_yscale('log')
ax3.set_ylim(0.3, 9000)
ax3.set_xticks(x)
ax3.set_xticklabels(configs_c, fontsize=9)
ax3.set_title('C. High-Res Multi-Lens Stress Test (4001x4001 Grid)', fontweight='bold', fontsize=11)
ax3.set_ylabel('Execution Time in ms (Log Scale)')
ax3.grid(True, linestyle='--', alpha=0.6, axis='y')
ax3.legend(loc='upper left')

# Add exact timing labels above bars in Graph C
for rect in rects1:
    h = rect.get_height()
    ax3.annotate(f"{h:.1f}", (rect.get_x() + rect.get_width()/2., h),
                 textcoords="offset points", xytext=(0, 3), ha='center', fontsize=7.5, fontweight='bold', color='#a93226')
for rect in rects2:
    h = rect.get_height()
    ax3.annotate(f"{h:.1f}", (rect.get_x() + rect.get_width()/2., h),
                 textcoords="offset points", xytext=(0, 3), ha='center', fontsize=7.5, color='#b9770e')
for rect in rects3:
    h = rect.get_height()
    ax3.annotate(f"{h:.2f}", (rect.get_x() + rect.get_width()/2., h),
                 textcoords="offset points", xytext=(0, 3), ha='center', fontsize=7.5, color='#1e8449')

plt.tight_layout()
plt.savefig('benchmark_graphs_report.png', dpi=300)
plt.show()
print("Saved benchmark_graphs_report.png matching Tables 3A, 3B, and 3C!")